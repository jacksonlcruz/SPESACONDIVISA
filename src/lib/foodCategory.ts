// ============================================================
//  Classificação alimentar dos produtos
//
//  Estratégia em três camadas (da mais confiável à menos):
//   1. `is_food` gravado no banco — definido pela IA do scanner
//      (GPT-4o Vision) ou pelo usuário no modal de edição.
//   2. Palpite por dicionário local (listas abaixo) — usado
//      quando a coluna ainda é `null` (item digitado à mão,
//      item antigo criado antes da migração).
//   3. Desconhecido → contabilizado em "non alimentari".
//
//  Bebidas: água, sucos, refrigerantes, café e chá são alimentícios.
//  Bebidas ALCOÓLICAS (vino, birra, superalcoólicos, cocktails) são
//  NÃO alimentícias, porque ticket/cartão alimentari não cobre álcool.
//  Rótulos "analcolico / senza alcol / alcohol free" são a exceção e
//  continuam alimentícios.
//
//  O dicionário é deliberadamente conservador: casa apenas
//  palavras inteiras (com plural simples), nunca prefixos.
//  Assim "Pannolini" não cai em "pane" e "Gel" não cai em
//  "gelato". Se errar, o usuário corrige no modal de edição
//  (o valor correto passa a ser persistido no banco).
// ============================================================

export type FoodKind = "food" | "nonfood" | "unknown";

/** Item mínimo necessário para resolver a categoria */
export interface CategorizableItem {
  name: string;
  is_food?: boolean | null;
}

/** Normaliza o nome: minúsculas, sem acentos, só letras e números */
function normalize(raw: string): string {
  return (raw ?? "")
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, " ")
    .trim();
}

